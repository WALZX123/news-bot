"""Explicit, resumable normalization of legacy database-generated timestamps.

Old RSS publication tuples already represent UTC. Only timestamps generated by
the old MySQL session need its explicitly supplied offset. DDL commits cannot
roll back, so the source timezone is committed before any legacy table changes.
"""
import json
import re


MIGRATION_KEY = 'legacy_timezone_v1'
LEGACY_TABLES = ('news_items', 'sent_logs', 'reports')


def _tables(cur):
    cur.execute("SELECT table_name FROM information_schema.tables WHERE table_schema=DATABASE() "
                "AND table_name IN ('news_items','sent_logs','reports','schema_meta')")
    return {row[0] for row in cur.fetchall()}


def _timezone(value):
    if value == 'UTC':
        value = '+00:00'
    if not isinstance(value, str) or not re.fullmatch(r'[+-]\d{2}:\d{2}', value):
        raise ValueError('legacy_timezone must be UTC or an explicit +/-HH:MM offset')
    hours, minutes = int(value[1:3]), int(value[4:6])
    if hours > 14 or minutes > 59 or (hours == 14 and minutes):
        raise ValueError('legacy_timezone offset is outside the supported range')
    offset = (hours * 60 + minutes) * (-1 if value[0] == '-' else 1)
    return ('+00:00' if offset == 0 else value), offset


def _state(cur, *, for_update=False):
    cur.execute('SELECT meta_value FROM schema_meta WHERE meta_key=%s' +
                (' FOR UPDATE' if for_update else ''), (MIGRATION_KEY,))
    row = cur.fetchone()
    if row is None:
        return None
    try:
        state = json.loads(row[0])
        if (not isinstance(state, dict) or state.get('status') not in ('pending', 'converted')
                or state.get('tables') != list(LEGACY_TABLES)):
            raise ValueError()
        zone, offset = _timezone(state.get('timezone'))
        if state.get('timezone') != zone or type(state.get('offset_minutes')) is not int or state['offset_minutes'] != offset:
            raise ValueError()
        return state
    except (ValueError, TypeError, KeyError):
        raise ValueError('Invalid legacy_timezone migration metadata; manual verification is required') from None


def prepare_legacy_timezone(store, legacy_timezone=None):
    """Persist legacy timezone intent before the caller starts additive DDL."""
    selected = _timezone(legacy_timezone) if legacy_timezone is not None else None
    with store.cursor() as cur:
        existing = _tables(cur)
        if 'schema_meta' in existing:
            state = _state(cur)
            if state:
                if selected and selected[0] != state['timezone']:
                    raise ValueError('legacy_timezone conflicts with the persisted migration timezone')
                return state
        if 'news_items' not in existing:
            return None
        cur.execute('SELECT COUNT(*) FROM information_schema.columns '
                    "WHERE table_schema=DATABASE() AND table_name='news_items' AND column_name='processing_state'")
        legacy = not cur.fetchone()[0]
    if not legacy:
        return None
    if not set(LEGACY_TABLES).issubset(existing):
        raise ValueError('Incomplete legacy database; verify the old tables before legacy_timezone migration')
    if selected is None:
        raise ValueError('legacy_timezone is required for the old database: use UTC or an explicit +/-HH:MM offset')
    state = {'status': 'pending', 'timezone': selected[0], 'offset_minutes': selected[1],
             'tables': list(LEGACY_TABLES)}
    # MySQL CREATE TABLE commits implicitly. No timestamp changes happen here.
    with store.cursor(write=True) as cur:
        cur.execute('CREATE TABLE IF NOT EXISTS schema_meta ('
                    'meta_key VARCHAR(64) PRIMARY KEY,meta_value TEXT NOT NULL) '
                    'ENGINE=InnoDB DEFAULT CHARSET=utf8mb4')
        cur.execute('INSERT IGNORE INTO schema_meta (meta_key,meta_value) VALUES (%s,%s)',
                    (MIGRATION_KEY, json.dumps(state, sort_keys=True)))
        persisted = _state(cur, for_update=True)
        if persisted != state:
            raise ValueError('legacy_timezone migration intent changed; retry after verifying the persisted timezone')
    return state


def finalize_legacy_timezone(store):
    """Complete the pending timestamp conversion after additive DDL succeeds."""
    with store.cursor(write=True) as cur:
        if 'schema_meta' not in _tables(cur):
            return None
        state = _state(cur, for_update=True)
        if state is None or state['status'] == 'converted':
            return state
        # These DML statements and the completion marker share one InnoDB
        # transaction. A crash rolls all of them back, preserving pending intent.
        for table, column in (('news_items', 'created_at'), ('sent_logs', 'sent_at'), ('reports', 'created_at')):
            cur.execute(f'UPDATE `{table}` SET `{column}`=TIMESTAMPADD(MINUTE,%s,`{column}`)',
                        (-state['offset_minutes'],))
        state['status'] = 'converted'
        cur.execute('UPDATE schema_meta SET meta_value=%s WHERE meta_key=%s',
                    (json.dumps(state, sort_keys=True), MIGRATION_KEY))
        return state
